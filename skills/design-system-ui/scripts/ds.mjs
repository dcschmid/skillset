#!/usr/bin/env node
// ds.mjs — design-system toolkit. Node stdlib only (runs on node >= 18).
// Zero dependencies by design: the skill's tooling must run anywhere the
// agent runs, without installs. Deep rules live in references/; this file
// only produces EVIDENCE (facts with file:line) — the agent decides.
//
// Usage:
//   node ds.mjs detect  [dir] [--format json|md]
//   node ds.mjs tokens  <tokens.json> [--themes light,dark] [--format json|md]
//   node ds.mjs audit   [dir] [--format json|md] [--max-files N]
//   node ds.mjs report  <results.json> [--format md|html] [--out file]
//
// Contracts:
//   detect  → stack facts {detected:[], unavailable:[]}; NEVER a decision.
//   tokens  → resolution + validation report; exit 1 on any P0 token error.
//             Checks DTCG v2025.10 (stable, CG-Final 2025-10-28) shape:
//             $type/$value/$description/$extensions; alias $ref chains;
//             cycles; missing targets; type/value mismatch; theme parity;
//             duplicate values; deprecation. No Style Dictionary needed.
//   audit   → findings with severity P0..P3, kind confirmed|heuristic,
//             evidence file:line. Reads CSS/SCSS/HTML/Vue/Svelte/JS/TS/TSX.
//   report  → renders findings JSON to md/html. Non-destructive: never
//             overwrites; collisions get a dated suffix.

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, basename, extname, relative } from 'node:path';

const args = process.argv.slice(2);
const command = args[0];
const rest = args.slice(1);

// ---------- arg helpers ----------
function flag(name, dflt) {
  const i = rest.indexOf(`--${name}`);
  if (i === -1) return dflt;
  const v = rest[i + 1];
  return v !== undefined && !v.startsWith('--') ? v : true;
}
const positional = rest.filter((a, i) => !a.startsWith('--') && !(rest[i - 1] || '').startsWith('--'));

// ---------- fs helpers ----------
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.next', '.output', 'out', 'coverage', 'vendor', '.svelte-kit', 'target', '.godot', '__pycache__']);
const TEXT_EXT = new Set(['.css', '.scss', '.sass', '.less', '.html', '.htm', '.js', '.mjs', '.cjs', '.ts', '.tsx', '.jsx', '.vue', '.svelte', '.astro', '.json', '.md']);
function readJSON(p) { try { return JSON.parse(readFileSync(p, 'utf8')); } catch { return null; } }
function readText(p, max = 400_000) { try { return readFileSync(p, 'utf8').slice(0, max); } catch { return null; } }
function* walk(dir, depth = 0) {
  if (depth > 12) return;
  let entries; try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
  for (const e of entries) {
    if (e.name.startsWith('.') && e.name !== '.gitignore') { if (e.isDirectory() && !e.name.startsWith('.git')) yield* walk(join(dir, e.name), depth + 1); continue; }
    const p = join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) yield* walk(p, depth + 1); }
    else if (TEXT_EXT.has(extname(e.name).toLowerCase())) yield p;
  }
}
function lineOf(text, index) { return text.slice(0, index).split('\n').length; }
function snippet(text, index, len = 70) {
  const s = text.slice(index, index + len).split('\n')[0].trim();
  return s.length >= len ? s + '…' : s;
}
function rel(root, p) { return relative(root, p) || basename(p); }

// ---------- comment/strip helpers (shallow; heuristic-safe) ----------
// Replaces comment chars with spaces so offsets/line numbers survive.
function stripComments(text) {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/gm, (m, p1) => p1 + ' '.repeat(m.length - p1.length));
}
function isGenerated(filePath, text) {
  const head = text.slice(0, 2000);
  return /generated|do not edit|autogenerated|@generated|nicht bearbeiten/i.test(head) || /\.(min|bundle)\.(js|css)$/.test(filePath);
}

// =====================================================================
// detect — stack facts for a project
// =====================================================================
function detect(root) {
  const detected = [], unavailable = [];
  const pkg = readJSON(join(root, 'package.json'));
  const deps = pkg ? { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) } : {};
  const has = (n) => Object.prototype.hasOwnProperty.call(deps, n);
  const ver = (n) => deps[n] || null;

  const frameworks = [
    ['react', 'react'], ['next', 'next'], ['astro', 'astro'], ['vue', 'vue'],
    ['svelte', 'svelte'], ['@angular/core', 'angular'], ['solid-js', 'solid'],
  ];
  for (const [pkgName, label] of frameworks)
    if (has(pkgName)) detected.push({ what: `framework:${label}`, evidence: `package.json ${pkgName}@${ver(pkgName)}` });
  if (!pkg) unavailable.push({ what: 'package.json', why: 'not found — not a node project or different layout' });

  const styling = [
    ['tailwindcss', 'tailwind'], ['@tailwindcss/vite', 'tailwind-v4'], ['styled-components', 'css-in-js:styled-components'],
    ['@emotion/react', 'css-in-js:emotion'], ['sass', 'sass'], ['less', 'less'],
  ];
  for (const [pkgName, label] of styling)
    if (has(pkgName)) detected.push({ what: `styling:${label}`, evidence: `package.json ${pkgName}@${ver(pkgName)}` });

  // css modules usage (fact, not inference about architecture)
  let modules = 0; for (const f of walk(root)) if (/\.module\.(css|scss|less)$/.test(f)) modules++;
  if (modules) detected.push({ what: 'styling:css-modules', evidence: `${modules} *.module.* files` });

  // token sources
  const tokenFiles = [];
  for (const f of walk(root)) {
    const b = basename(f);
    if (/tokens?/.test(b) && /\.(json|json5)$/.test(b) && !/package(-lock)?\.json/.test(b)) {
      const t = readText(f, 4000) || '';
      if (/\$type|"value"|:\s*"[^"]*"\s*[},]/.test(t)) tokenFiles.push(rel(root, f));
    }
  }
  if (tokenFiles.length) detected.push({ what: 'tokens:dtcg-candidates', evidence: tokenFiles.slice(0, 8).join(', ') + (tokenFiles.length > 8 ? ` (+${tokenFiles.length - 8})` : '') });
  else unavailable.push({ what: 'tokens:dtcg', why: 'no token JSON source files found' });

  // design tooling
  for (const [pkgName, label] of [['style-dictionary', 'style-dictionary'], ['storybook', 'storybook'], ['@storybook/react', 'storybook'], ['axe-core', 'axe-core'], ['@playwright/test', 'playwright'], ['vitest', 'vitest'], ['radix-ui', 'radix'], ['@radix-ui/react-dialog', 'radix'], ['react-aria', 'react-aria'], ['@shadcn/ui', 'shadcn'], ['lucide-react', 'icons:lucide'], ['@fontsource', 'fonts:fontsource']])
    if (has(pkgName)) detected.push({ what: `tooling:${label}`, evidence: `package.json ${pkgName}@${ver(pkgName)}` });

  // theme mechanism facts
  const theme = { dark: 0, prefersColorScheme: 0, reducedMotion: 0, customProps: 0 };
  for (const f of walk(root)) {
    if (!/\.(css|scss|astro|svelte|vue|js|ts|tsx|jsx|html)$/.test(f)) continue;
    const t = readText(f, 200_000); if (!t) continue;
    if (/\.dark\b|data-theme=|\[data-theme/.test(t)) theme.dark++;
    if (/prefers-color-scheme/.test(t)) theme.prefersColorScheme++;
    if (/prefers-reduced-motion/.test(t)) theme.reducedMotion++;
    const m = t.match(/--[a-z][\w-]*\s*:/gi); if (m) theme.customProps += m.length;
  }
  if (theme.dark) detected.push({ what: 'theming:dark', evidence: `${theme.dark} files with .dark/data-theme` }); else unavailable.push({ what: 'theming:dark', why: 'no dark-mode mechanism found' });
  if (theme.prefersColorScheme) detected.push({ what: 'theming:prefs-color-scheme', evidence: `${theme.prefersColorScheme} files` });
  if (theme.reducedMotion) detected.push({ what: 'theming:prefs-reduced-motion', evidence: `${theme.reducedMotion} files` });
  if (theme.customProps) detected.push({ what: 'styling:custom-properties', evidence: `${theme.customProps} declarations` });

  // game engines
  if (existsSync(join(root, 'game.project'))) detected.push({ what: 'engine:defold', evidence: 'game.project present' });
  if (existsSync(join(root, 'project.godot'))) detected.push({ what: 'engine:godot', evidence: 'project.godot present' });

  // language / i18n surface
  const locFiles = [];
  for (const f of walk(root)) if (/(locales?|i18n|lang)[\\/][^/]+\.(json|ts|js)$/.test(f) || /[^/]+\.(en|de|fr|es|it|pt|nl|pl|cs)\.json$/.test(f)) locFiles.push(rel(root, f));
  if (locFiles.length) detected.push({ what: 'i18n:locale-files', evidence: locFiles.slice(0, 6).join(', ') + (locFiles.length > 6 ? ' …' : '') });

  // component dir convention
  const compDirs = [];
  for (const d of ['src/components', 'components', 'src/ui', 'ui', 'src/lib/components', 'lib/components'])
    if (existsSync(join(root, d))) compDirs.push(d);
  if (compDirs.length) detected.push({ what: 'components:dirs', evidence: compDirs.join(', ') });

  // tests + quality gates actually wired
  const scripts = pkg && pkg.scripts ? Object.entries(pkg.scripts).filter(([, v]) => /(test|lint|check|storybook|build)/.test(v)).map(([k]) => k) : [];
  if (scripts.length) detected.push({ what: 'scripts:quality-gates', evidence: scripts.join(', ') });
  else if (pkg) unavailable.push({ what: 'scripts:quality-gates', why: 'package.json has no test/lint/check/build scripts' });

  const lock = ['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb'].find((l) => existsSync(join(root, l)));
  if (lock) detected.push({ what: 'package-manager:lockfile', evidence: lock });

  return { project: basename(root) || root, detected, unavailable, note: 'facts only; framework decisions belong to the caller and its framework skills' };
}

// =====================================================================
// tokens — DTCG v2025.10 source validation + resolution
// =====================================================================
const DTCG_TYPES = new Set(['color', 'dimension', 'fontFamily', 'fontWeight', 'duration', 'number', 'cubicBezier', 'gradient', 'shadow', 'image', 'link']);
// type → value-shape predicate (value already alias-resolved)
const VALUE_SHAPE = {
  color: (v) => typeof v === 'string' && (/^#[0-9a-fA-F]{3,8}$/.test(v.trim()) || /^(rgb|rgba|hsl|hsla)\(/.test(v.trim()) || /^[a-zA-Z]+$/i.test(v.trim())),
  dimension: (v) => typeof v === 'string' && /^-?[\d.]+(px|rem|em|%|vh|vw|pt|pc|in|cm|mm|ex|ch)?$/.test(v.trim().replace(/\s+/g, '')),
  duration: (v) => typeof v === 'string' && /^-?[\d.]+(ms|s)$/.test(v.trim()),
  number: (v) => typeof v === 'number',
  fontWeight: (v) => typeof v === 'number' || (typeof v === 'string' && /^(thin|extralight|light|normal|medium|semibold|bold|extrabold|black|-?[\d.]+)$/i.test(v.trim())),
  fontFamily: (v) => typeof v === 'string' || Array.isArray(v),
  cubicBezier: (v) => Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === 'number'),
  gradient: (v) => Array.isArray(v), shadow: (v) => typeof v === 'object' && v !== null,
  image: (v) => typeof v === 'string', link: (v) => typeof v === 'string',
};
function shapeOk(type, value) {
  const f = VALUE_SHAPE[type];
  if (!f) return true;
  try { return !!f(value); } catch { return false; }
}

function tokensMain(file, themeNames) {
  const abs = resolve(file);
  const raw = readText(abs);
  if (raw === null) { console.error(`tokens: cannot read ${file}`); process.exit(2); }
  let doc; try { doc = JSON.parse(raw); } catch (e) { console.error(`tokens: invalid JSON: ${e.message}`); process.exit(2); }

  const themes = themeNames.length ? themeNames : null;
  // collect $theme entries: { themeName: groupRoot }
  if (themes) for (const th of themes) if (!doc[th] || typeof doc[th] !== 'object') { console.error(`tokens: theme group "${th}" missing in ${file}`); process.exit(1); }

  // flatten: path → { $type?, $value, $ref?, ... , values: {theme|__default: raw} }
  const problems = [];
  const seenProb = new Set();
  const prob = (severity, code, where, detail) => { const k = `${code}|${where}`; if (!seenProb.has(k)) { seenProb.add(k); problems.push({ severity, code, where, detail }); } };
  const flat = new Map();
  const seenName = new Map();
  function isToken(o) { return o && typeof o === 'object' && !Array.isArray(o) && ('$value' in o || '$type' in o); }
  function walkGroup(node, path, type, theme) {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('$')) continue;
      if (themes && !path && themes.includes(k)) continue; // theme groups walked separately
      const key = path ? `${path}.${k}` : k;
      if (isToken(v)) {
        const t = v.$type || type || null;
        if (t && !DTCG_TYPES.has(t) && !String(t).startsWith('com')) problems.push({ severity: 'P2', code: 'unknown-type', where: key, detail: `$type "${t}" is not a DTCG type` });
        let entry = flat.get(key);
        if (!entry) { entry = { values: {}, type: t, desc: v.$description || '', deprecated: !!(v.$extensions && v.$extensions.deprecated) }; flat.set(key, entry); }
        if (theme) entry.values[theme] = v.$value; else entry.values.__default = v.$value;
        if (!entry.type && t) entry.type = t;
        if (!theme) { // same leaf name on two different shared tokens → aliasing preferred
          if (seenName.has(k) && seenName.get(k) !== key) problems.push({ severity: 'P3', code: 'duplicate-name', where: `${key} vs ${seenName.get(k)}`, detail: `token name "${k}" used in two places` });
          else seenName.set(k, key);
        }
      } else if (v && typeof v === 'object') walkGroup(v, key, v.$type || type, theme);
    }
  }
  walkGroup(doc, '', null, null); // shared tokens (in theme mode, theme groups are skipped here)
  if (themes) for (const th of themes) walkGroup((doc[th] && typeof doc[th] === 'object' && !('$value' in doc[th])) ? doc[th] : {}, '', null, th);
  for (const [k, e] of flat) if (!Object.keys(e.values).length) flat.delete(k); // group-only

  const aliasRe = (v) => typeof v === 'string' && /^\{([\w.$[\]-]+)\}$/.test(v.trim()) ? v.trim().slice(1, -1) : null;
  // value of an alias target for theme th: theme override → shared default
  function valueFor(entry, th) {
    if (!themes || th === '__default') return entry.values.__default;
    if (Object.prototype.hasOwnProperty.call(entry.values, th)) return entry.values[th];
    if (Object.prototype.hasOwnProperty.call(entry.values, '__default')) return entry.values.__default;
    return undefined;
  }
  function resolveValue(raw, theme, chain = []) {
    const target = aliasRe(raw);
    if (target === null) return { ok: true, value: raw };
    if (chain.includes(target)) return { ok: false, cycle: [...chain, target].join(' → ') };
    const entry = flat.get(target);
    if (!entry) return { ok: false, missing: target };
    const next = valueFor(entry, theme);
    if (next === undefined) return { ok: false, missing: `${target} (no value for theme ${theme})` };
    return resolveValue(next, theme, [...chain, target]);
  }

  const resolved = {};
  const stats = { tokens: flat.size, themes: themes ? themes.length : 1, aliases: 0, deprecated: 0, themed: 0 };
  for (const [key, entry] of flat) {
    if (entry.deprecated) stats.deprecated++;
    const isThemed = Object.keys(entry.values).some((t) => t !== '__default');
    if (isThemed) stats.themed++;
    const perTheme = {};
    for (const th of themes ? themes : ['__default']) {
      const raw = isThemed ? entry.values[th] : entry.values.__default;
      if (raw === undefined) { problems.push({ severity: 'P1', code: 'theme-parity', where: key, detail: `token defined for other themes but missing in "${th}"` }); continue; }
      const r = resolveValue(raw, th);
      if (!r.ok) {
        if (r.cycle) prob('P0', 'circular-ref', key, `circular alias: ${r.cycle}`);
        else prob('P0', 'missing-ref', key, `alias {${r.missing}} does not resolve`);
        continue;
      }
      if (aliasRe(raw) !== null) stats.aliases++;
      if (entry.type && !String(entry.type).startsWith('com') && !shapeOk(entry.type, r.value))
        prob('P1', 'type-mismatch', key, `$type ${entry.type} but resolved value ${JSON.stringify(r.value).slice(0, 60)} has wrong shape`);
      perTheme[th] = r.value;
    }
    resolved[key] = { type: entry.type, themes: perTheme };
  }

  // duplicate resolved values (primitives duplicating each other)
  const valueIndex = new Map();
  for (const [key, e] of Object.entries(resolved)) {
    const first = Object.values(e.themes)[0];
    if (first !== null && first !== undefined && typeof first !== 'object') {
      const v = JSON.stringify(first);
      if (!valueIndex.has(v)) valueIndex.set(v, []);
      valueIndex.get(v).push(key);
    }
  }
  for (const [v, keys] of valueIndex) if (keys.length > 1 && keys.length <= 6)
    prob('P3', 'duplicate-value', keys.join(', '), `identical value ${v} — consider one token + aliases`);

  return { source: abs.split('/').slice(-2).join('/'), spec: 'DTCG v2025.10 (CG-Final 2025-10-28)', stats, problems, resolved: themes ? resolved : Object.fromEntries(Object.entries(resolved).map(([k, e]) => [k, { type: e.type, value: Object.values(e.themes)[0] }])) };
}

// =====================================================================
// audit — evidence findings on styling consistency
// =====================================================================
function audit(root, maxFiles) {
  const findings = [];
  const push = (f) => findings.push(f);
  const all = [...walk(root)];
  const genSet = new Set(all.filter((f) => isGenerated(f, readText(f, 3000) || '')));
  const scanned = all.filter((f) => !genSet.has(f)).slice(0, maxFiles);
  const genScanned = all.filter((f) => genSet.has(f)).slice(0, maxFiles); // var decls/dark blocks only

  const hexIndex = new Map(); const rgbaIndex = new Map(); const remIndex = new Map();
  const zIndexSeen = new Map();
  const varDecls = new Map(); const varUses = new Map(); const darkBlocks = [];
  let importantCount = 0, inlineStyleCount = 0, transitionAll = 0;
  const fontSizes = new Map(); const lineHeights = new Map(); const radii = new Map();
  const btnRoots = new Set(); let focusStyled = 0, outlineNone = 0, reducedMotion = 0;

  for (const file of scanned) {
    const raw = readText(file); if (raw === null) continue;
    const text = file.endsWith('.css') || file.endsWith('.scss') ? raw : stripComments(raw);
    const r = rel(root, file);
    const isCss = /\.(css|scss|sass|less)$/.test(file);
    const isTpl = /\.(astro|svelte|vue|html|htm|tsx|jsx)$/.test(file);

    // hardcoded hex colors (P2 tokenization finding; contrast impact noted)
    for (const m of text.matchAll(/#([0-9a-fA-F]{3,8})\b/g)) {
      const val = '#' + m[1].toLowerCase();
      const key = val.length === 4 ? '#' + [...m[1].toLowerCase()].map((c) => c + c).join('') : val;
      if (!hexIndex.has(key)) hexIndex.set(key, []);
      hexIndex.get(key).push({ at: `${r}:${lineOf(raw, m.index)}`, snip: snippet(raw, m.index, 50) });
    }
    // rgba() literals with alpha (theme-opacity risk)
    for (const m of text.matchAll(/rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*,?\s*([\d.]+)?\s*\)/g)) {
      const key = m[0].replace(/\s+/g, '');
      if (!rgbaIndex.has(key)) rgbaIndex.set(key, []);
      rgbaIndex.get(key).push({ at: `${r}:${lineOf(raw, m.index)}`, snip: snippet(raw, m.index, 50) });
    }
    // !important
    for (const m of text.matchAll(/!important/g)) importantCount++;
    // transition: all
    for (const m of text.matchAll(/transition(?:-property)?\s*:\s*[^;]*\ball\b/g)) transitionAll++;
    // inline style= (heuristic duplication source)
    if (isTpl) for (const m of raw.matchAll(/\bstyle=\{?["'`{]/g)) inlineStyleCount++;
    // focus handling facts
    outlineNone += (text.match(/outline\s*:\s*none(?![\s\w-])|outline:\s*none\s*(?=[;}])/g) || []).length - (text.match(/outline\s*:\s*none\s+(!important)?\s*(box-shadow|outline)/g) || []).length;
    focusStyled += (text.match(/:focus(-visible)?\b/g) || []).length;
    reducedMotion += (text.match(/prefers-reduced-motion/g) || []).length;

    // rem spacing scale (padding/gap/margin single values)
    for (const m of text.matchAll(/\b(?:padding|margin|gap|row-gap|column-gap|inset)\s*:\s*([^;{}]+)/g)) {
      for (const v of m[1].matchAll(/(\d*\.?\d+)rem\b/g)) {
        const key = v[1] + 'rem';
        if (!remIndex.has(key)) remIndex.set(key, 0);
        remIndex.set(key, remIndex.get(key) + 1);
      }
    }
    // font sizes / line heights / radii scatter
    for (const m of text.matchAll(/font-size\s*:\s*([^;{}]+)/g)) { const v = m[1].trim().split(/\s+/)[0]; fontSizes.set(v, (fontSizes.get(v) || 0) + 1); }
    for (const m of text.matchAll(/line-height\s*:\s*([^;{}]+)/g)) { const v = m[1].trim().split(/\s+/)[0]; lineHeights.set(v, (lineHeights.get(v) || 0) + 1); }
    for (const m of text.matchAll(/border-radius\s*:\s*([^;{}]+)/g)) { const v = m[1].trim().split(/\s+/)[0]; if (!/var\(|0(px|r|em)?\s*$|^0$/.test(v)) radii.set(v, (radii.get(v) || 0) + 1); }
    for (const m of text.matchAll(/z-index\s*:\s*([^;{}\s]+)/g)) { const v = m[1].trim(); if (!/var\(|inherit|auto/.test(v)) { const k = v.padStart(6); if (!zIndexSeen.has(k)) zIndexSeen.set(k, []); zIndexSeen.get(k).push(`${r}:${lineOf(raw, m.index)}`); } }
    // z-index ordering collisions handled via zIndexSeen below
    // custom properties: declared vs used
    for (const m of text.matchAll(/(--[\w-]+)\s*:/g)) { const n = m[1]; varDecls.set(n, (varDecls.get(n) || 0) + 1); }
    for (const m of text.matchAll(/var\(\s*(--[\w-]+)/g)) { const n = m[1]; varUses.set(n, (varUses.get(n) || 0) + 1); }
    // dark theme blocks: collect selector presence per file
    if (/(prefers-color-scheme\s*:\s*dark|\.dark\b|\[data-theme=["']?dark)/.test(text)) darkBlocks.push(r);
    // button-ish selectors
    for (const m of text.matchAll(/(?:\.([\w-]*btn[\w-]*|[\w-]*button[\w-]*)\b|<Button\b|<button\b)/g)) {
      const root = m[1] ? m[1].split(/--|__|:/)[0] : 'tag:button';
      btnRoots.add(root);
    }
    // duplicated declarations inside same block (same prop twice in one { } block)
    if (isCss) {
      for (const block of text.matchAll(/\{([^{}]*)\}/g)) {
        const props = new Map();
        for (const d of block[1].matchAll(/([a-z-]+)\s*:\s*[^;]+/gi)) {
          const p = d[1]; props.set(p, (props.get(p) || 0) + 1);
        }
        for (const [p, n] of props) if (n > 1 && !/(gap|padding|margin|background|color|grid-template)/.test(p)) {
          push({ severity: 'P2', kind: 'confirmed', rule: 'duplicate-declaration', file: r, line: lineOf(raw, block.index), detail: `"${p}" declared ${n}× in one rule block — later wins; earlier is dead`, evidence: snippet(raw, block.index, 60) });
        }
      }
    }
  }
  // generated files (tokens.css): declare vars / dark blocks, but never findings
  for (const file of genScanned) {
    const raw = readText(file); if (!raw) continue;
    for (const m of raw.matchAll(/(--[\w-]+)\s*:/g)) { const n = m[1]; varDecls.set(n, (varDecls.get(n) || 0) + 1); }
    if (/prefers-color-scheme\s*:\s*dark|\[data-theme=["']?dark|\.dark\b/.test(raw)) darkBlocks.push(rel(root, file));
  }


  // ---- roll up findings ----
  const out = [];
  for (const [key, occ] of hexIndex) if (occ.length >= 2)
    out.push({ severity: 'P2', kind: 'confirmed', rule: 'hardcoded-color', detail: `${occ.length}× hardcoded ${key} — candidate for a semantic token`, evidence: occ.slice(0, 4).map((o) => o.at).join(', ') + (occ.length > 4 ? ` (+${occ.length - 4})` : ''), impact: 'theme switches and contrast fixes cannot target these' });
  for (const [key, occ] of rgbaIndex) if (occ.length >= 3)
    out.push({ severity: 'P2', kind: 'confirmed', rule: 'hardcoded-rgba', detail: `${occ.length}× literal ${key} — alpha literals break on dark backgrounds`, evidence: occ.slice(0, 4).map((o) => o.at).join(', ') });
  // odd hex (needs manual contrast review)
  for (const f of findings) out.push(f);
  const oddHex = [...hexIndex.keys()].filter((h) => { const [r, g, b] = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)); const L = (0.2126 * srgb(r) + 0.7152 * srgb(g) + 0.0722 * srgb(b)); return L > 0.18 && L < 0.82; });
  if (oddHex.length) out.push({ severity: 'P2', kind: 'heuristic', rule: 'contrast-review', detail: `${oddHex.length} mid-luminance colors need manual contrast check in BOTH themes (L 0.18–0.82): ${oddHex.slice(0, 6).join(' ')}${oddHex.length > 6 ? ' …' : ''}`, impact: 'automated contrast gates need a browser; these are review candidates' });
  // rem scatter
  const remVals = [...remIndex.entries()].filter(([, n]) => n === 1).sort((a, b) => parseFloat(a[0]) - parseFloat(b[0]));
  if (remVals.length >= 6) out.push({ severity: 'P2', kind: 'confirmed', rule: 'spacing-scale', detail: `${remVals.length} one-off rem values (1× each) — no shared spacing scale: ${remVals.slice(0, 10).map(([v]) => v).join(' ')}${remVals.length > 10 ? ' …' : ''}`, impact: 'spacing drift; snap to 4px scale or define tokens', evidence: remVals.slice(0, 6).map(([v]) => remIndex.get(v)).join('') ? `${remVals.length} single-use values` : '' });
  const fsVals = [...fontSizes.entries()].filter(([, n]) => n === 1);
  if (fsVals.length >= 8) out.push({ severity: 'P2', kind: 'confirmed', rule: 'type-scale', detail: `${fsVals.length} one-off font-size values — typography scale not enforced` });
  if (lineHeights.size >= 8) out.push({ severity: 'P2', kind: 'heuristic', rule: 'line-height-scatter', detail: `${lineHeights.size} distinct line-height values — check against the type scale` });
  if (radii.size >= 6) out.push({ severity: 'P3', kind: 'heuristic', rule: 'radius-scatter', detail: `${radii.size} distinct border-radius values: ${[...radii.keys()].slice(0, 8).join(' ')} — radius should come from few tokens` });
  if (zIndexSeen.size >= 4) out.push({ severity: 'P2', kind: 'heuristic', rule: 'z-index', detail: `${zIndexSeen.size} distinct z-index literals (${[...zIndexSeen.keys()].slice(0, 8).join(' ')}) — needs a layer convention/token set` });
  if (importantCount >= 5) out.push({ severity: 'P2', kind: 'confirmed', rule: 'important-spam', detail: `${importantCount}× !important across ${scanned.length} files — specificity battles; refactor cascade instead` });
  if (transitionAll >= 3) out.push({ severity: 'P2', kind: 'confirmed', rule: 'transition-all', detail: `${transitionAll}× transition:all — performance + unintended animation; name properties` });
  if (inlineStyleCount >= 8) out.push({ severity: 'P2', kind: 'heuristic', rule: 'inline-styles', detail: `${inlineStyleCount}× inline style= in templates — duplication source; move to classes/tokens` });
  if (outlineNone >= 1) out.push({ severity: 'P0', kind: 'confirmed', rule: 'focus-hidden', detail: `${outlineNone}× outline:none without visible replacement — keyboard users lose focus`, impact: 'WCAG 2.4.7 keyboard trap risk' });
  if (focusStyled > 0 && reducedMotion === 0) out.push({ severity: 'P2', kind: 'heuristic', rule: 'reduced-motion', detail: `motion present but zero prefers-reduced-motion handling` });
  // custom prop: declared but never used / used but never declared
  const deadVars = [...varDecls.keys()].filter((v) => !varUses.has(v));
  const undefVars = [...varUses.keys()].filter((v) => !varDecls.has(v));
  if (deadVars.length >= 5) out.push({ severity: 'P2', kind: 'heuristic', rule: 'unused-custom-props', detail: `${deadVars.length} custom properties declared but never referenced (first: ${deadVars.slice(0, 4).join(' ')} …) — dead or source-of-truth; verify before delete` });
  if (undefVars.length >= 1) out.push({ severity: 'P1', kind: 'heuristic', rule: 'undefined-custom-props', detail: `${undefVars.length} var(--*) referenced without a declaration in scan scope (${undefVars.slice(0, 4).join(' ')} …) — could be declared in an unscanned file`, impact: 'missing var = unset styles at runtime' });
  // dark mode coverage
  const lightVarTokens = varDecls.size;
  if (lightVarTokens > 10 && darkBlocks.length === 0) out.push({ severity: 'P1', kind: 'heuristic', rule: 'dark-coverage', detail: `${lightVarTokens} custom properties but no dark-theme block anywhere — dark mode absent or tokenized elsewhere` });
  else if (darkBlocks.length >= 2) {
    const multiDark = darkBlocks.length;
    out.push({ severity: 'P3', kind: 'heuristic', rule: 'dark-fragmented', detail: `dark-mode overrides live in ${multiDark} files (${darkBlocks.slice(0, 4).join(', ')}${darkBlocks.length > 4 ? ' …' : ''}) — one theme source is maintainable-er` });
  }
  // button variants
  if (btnRoots.size >= 3) out.push({ severity: 'P1', kind: 'heuristic', rule: 'button-variants', detail: `${btnRoots.size} button roots (${[...btnRoots].slice(0,5).join(" ")} — check for duplicated button implementations` });

  // sort by severity
  const rank = { P0: 0, P1: 1, P2: 2, P3: 3 };
  out.sort((a, b) => rank[a.severity] - rank[b.severity]);
  return { project: basename(root) || root, filesScanned: scanned.length, totalFiles: all.length, truncated: all.length - scanned.length > 0, thresholds: 'repeat-count thresholds are defaults; tune per project', findings: out };
}
function srgb(c) { c /= 255; return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); }

// =====================================================================
// report — render findings/token JSON to md/html (non-destructive)
// =====================================================================
function renderReport(data, fmt) {
  const title = data.project || data.source || 'design-system report';
  const items = data.findings || (data.problems ? data.problems.map((p) => ({ ...p, detail: p.detail, rule: p.code, evidence: p.where })) : []);
  const sev = { P0: 0, P1: 1, P2: 2, P3: 3 };
  items.sort((a, b) => (sev[a.severity] ?? 9) - (sev[b.severity] ?? 9));
  const counts = items.reduce((m, f) => ((m[f.severity] = (m[f.severity] || 0) + 1), m), {});
  const autoFixable = items.filter((f) => ['hardcoded-color', 'hardcoded-rgba', 'duplicate-declaration', 'spacing-scale'].includes(f.rule)).length;
  const needsDesign = items.length - autoFixable;
  if (fmt === 'html') {
    const rows = items.map((f) => `<tr><td>${f.severity}</td><td>${f.kind || ''}</td><td>${esc(f.rule || '')}</td><td>${esc(f.detail || '')}</td><td><code>${esc(String(f.evidence || '')).slice(0, 120)}</code></td><td>${esc(f.impact || '')}</td></tr>`).join('\n');
    return `<!doctype html><meta charset="utf-8"><title>${esc(title)}</title>
<style>body{font:14px/1.5 system-ui;max-width:1100px;margin:2rem auto;padding:0 1rem}table{border-collapse:collapse;width:100%}td,th{border:1px solid #bbb;padding:.4em .6em;text-align:left;vertical-align:top}code{font-size:.9em}</style>
<h1>${esc(title)}</h1><p>${Object.entries(counts).map(([k, v]) => `<b>${k}</b> ${v}`).join(' · ')} · auto-fixable ~${autoFixable} · design decisions ${needsDesign}</p>
<table><thead><tr><th>P</th><th>kind</th><th>rule</th><th>detail</th><th>evidence</th><th>impact</th></tr></thead><tbody>${rows}</tbody></table>
<p>automated evidence ≠ conformance; heuristics need human confirm</p>`;
  }
  const lines = [`# ${title}`, '', Object.entries(counts).map(([k, v]) => `**${k}:** ${v}`).join(' · ') + ` — auto-fixable ≈${autoFixable}, design decisions ≈${needsDesign}`, ''];
  for (const f of items) lines.push(`- **${f.severity}** [${f.kind || '-'}] \`${f.rule || ''}\` — ${f.detail}${f.evidence ? `\n  - evidence: \`${String(f.evidence).slice(0, 160)}\`` : ''}${f.impact ? `\n  - impact: ${f.impact}` : ''}`);
  lines.push('', 'automated evidence ≠ conformance; heuristics need human confirm');
  return lines.join('\n');
}
function esc(s) { return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

